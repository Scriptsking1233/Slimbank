create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- счета
create table if not exists public.accounts (
  id           bigint generated by default as identity primary key,
  login_id     text not null unique,
  phone        text,
  email        text,
  username     text,
  pass_hash    text not null,
  plan         text default 'basic',
  balance      numeric(40,2) default 0,
  last_accrual bigint default 0,
  state        jsonb default '{}'::jsonb,
  token        uuid,
  token_exp    timestamptz,
  created_at   timestamptz default now(),
  updated_at   timestamptz default now()
);

create unique index if not exists accounts_username_uniq
  on public.accounts (lower(username)) where username is not null;
create index if not exists accounts_token_idx on public.accounts (token);
create index if not exists accounts_balance_idx on public.accounts (balance desc);

-- таблица закрыта напрямую: всё только через функции ниже
alter table public.accounts enable row level security;
revoke all on table public.accounts from anon, authenticated;

